// -------------------------------------------------------------------
// Инициализация таблицы векторов прерываний
// Должна быть вызвана ДО main
// -------------------------------------------------------------------

func_init_vectors:
    // вектор 0: print_int
    LDI r0, 0
    LDI r1, int0_handler
    CALL func_set_int_vector
    LDI r0, 1
    LDI r1, int1_handler
    CALL func_set_int_vector
    LDI r0, 2
    LDI r1, int2_handler
    CALL func_set_int_vector
    RET

// -------------------------------------------------------------------
// func_set_int_vector(vector, handler) – установить обработчик
//   r0 = номер вектора
//   r1 = адрес обработчика
// -------------------------------------------------------------------

func_set_int_vector:
    // tableBase = 0x0
    LDI r2, 0x0
    MOV r3, r0
    // r3 = vector * 8
    ADD r3, r3
    ADD r3, r3
    ADD r3, r3
    ADD r2, r3
    // записать handler по адресу в r2
    STORE_IND.S64 r1, r2
    RET

// -------------------------------------------------------------------
// Обработчик 0: print_int – печатает целое из r0
// Сохраняет r0, чтобы не испортить вызывающую программу
// -------------------------------------------------------------------

int0_handler:
    PUSH r0
    PRINT_INT r0
    POP r0
    IRET

// -------------------------------------------------------------------
// Обработчик 1: _out_port – вывод байта в порт
//   r0 = порт, r1 = значение
// -------------------------------------------------------------------

int1_handler:
    PUSH r0
    PUSH r1
    OUT r1, r0
    POP r1
    POP r0
    IRET

// -------------------------------------------------------------------
// Обработчик 2: _in_port – чтение байта из порта
//   r0 = порт, возврат значения в r0
// -------------------------------------------------------------------

int2_handler:
    IN r0, r0
    IRET

// -------------------------------------------------------------------
// Публичные обёртки для системных вызовов
// -------------------------------------------------------------------

func_print_int:
    LDI r2, 0
    INT r2
    RET

func_out_port:
    LDI r2, 1
    INT r2
    RET

func_in_port:
    LDI r2, 2
    INT r2
    RET

func_exit:
    HALT
    RET