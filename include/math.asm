// math.asm – Arithmetic and logical extensions

// -------------------------------------------------------------------
// Умножение двух чисел (использует встроенный MULT_INT)
// Вход: r0 = a, r1 = b
// Возврат: r0 = a * b
// -------------------------------------------------------------------
func_multiply:
	MULT_INT r0, r1
	RET

// -------------------------------------------------------------------
// Деление (использует встроенный DIV)
// Вход: r0 = делимое, r1 = делитель
// Возврат: r0 = частное
// -------------------------------------------------------------------
func_divide:
	DIV r0, r1
	RET

// -------------------------------------------------------------------
// Остаток от деления (a % b)
// Вход: r0 = a, r1 = b
// Возврат: r0 = a % b
// -------------------------------------------------------------------
func_modulo:
	PUSH r2
	PUSH r3
	MOV r2, r0      // сохраняем a
	DIV r0, r1      // r0 = a / b
	MULT_INT r0, r1 // r0 = (a/b) * b
	SUB r2, r0      // r2 = a - (a/b)*b = остаток
	MOV r0, r2
	POP r3
	POP r2
	RET

// -------------------------------------------------------------------
// Возведение в степень (целое, положительное)
// Вход: r0 = основание, r1 = показатель степени
// Возврат: r0 = base^exp
// -------------------------------------------------------------------
func_power:
	PUSH r2
	PUSH r3
	MOV r2, r0      // base
	MOV r3, r1      // exp
	LDI r0, 1       // result = 1
power_loop:
	JZ power_done   // если exp == 0, выход
	MULT_INT r0, r2 // result *= base
	DEC r3          // exp--
	MOV r1, r3
	JMP power_loop
power_done:
	POP r3
	POP r2
	RET

// -------------------------------------------------------------------
// Сдвиг влево (r0 << r1)
// Вход: r0 = число, r1 = количество бит
// Возврат: r0 = результат
// -------------------------------------------------------------------
func_shift_left:
	// Умножение на 2^r1 через цикл сложений
	PUSH r2
	MOV r2, r1
	LDI r1, 2
shift_left_loop:
	JZ shift_left_done
	MULT_INT r0, r1
	DEC r2
	MOV r1, r2
	JMP shift_left_loop
shift_left_done:
	POP r2
	RET

// -------------------------------------------------------------------
// Сдвиг вправо (r0 >> r1) – использует SHR
// Вход: r0 = число, r1 = количество бит
// Возврат: r0 = результат
// -------------------------------------------------------------------
func_shift_right:
	SHR r0, r1
	RET

// -------------------------------------------------------------------
// Максимум из двух чисел
// Вход: r0 = a, r1 = b
// Возврат: r0 = max(a,b)
// -------------------------------------------------------------------
func_max:
	PUSH r2
	MOV r2, r0
	SUB r2, r1      // r2 = a - b, обновит флаги
	JG a_greater
	MOV r0, r1      // b больше или равно
	POP r2
	RET
a_greater:
	MOV r0, r2      // восстановим a (r2 было изменено вычитанием)
	POP r2
	RET

// -------------------------------------------------------------------
// Минимум из двух чисел
// Вход: r0 = a, r1 = b
// Возврат: r0 = min(a,b)
// -------------------------------------------------------------------
func_min:
	PUSH r2
	MOV r2, r0
	SUB r2, r1
	JL a_less
	MOV r0, r1
	POP r2
	RET
a_less:
	MOV r0, r2
	POP r2
	RET

// -------------------------------------------------------------------
// Абсолютное значение (|r0|)
// -------------------------------------------------------------------
func_abs:
	PUSH r1
	MOV r1, r0
	LDI r0, 0
	SUB r0, r1      // r0 = -r1, флаги
	JG negative
	MOV r0, r1      // было положительное
	POP r1
	RET
negative:
	// r0 уже содержит -r1
	POP r1
	RET

func_double:
	ADD r0, r0
	RET

